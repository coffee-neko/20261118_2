CREATE TABLE IF NOT EXISTS todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    display_order INT NOT NULL DEFAULT 0
);

-- Backfill only rows from the legacy schema and keep any status already stored.
ALTER TABLE todos ADD COLUMN IF NOT EXISTS completed BOOLEAN;
ALTER TABLE todos ADD COLUMN IF NOT EXISTS status VARCHAR(20);
UPDATE todos
SET status = CASE WHEN completed = TRUE THEN 'COMPLETED' ELSE 'NOT_STARTED' END
WHERE status IS NULL;
ALTER TABLE todos ALTER COLUMN status SET DEFAULT 'NOT_STARTED';
ALTER TABLE todos ALTER COLUMN status SET NOT NULL;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS chk_todos_status
    CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'));
ALTER TABLE todos DROP COLUMN IF EXISTS completed;

CREATE INDEX IF NOT EXISTS idx_todos_display_order_id
    ON todos (display_order, id);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS start_date DATE;
ALTER TABLE todos ADD COLUMN IF NOT EXISTS due_date DATE;

ALTER TABLE todos ADD COLUMN IF NOT EXISTS parent_id BIGINT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS fk_todos_parent
    FOREIGN KEY (parent_id) REFERENCES todos (id) ON DELETE RESTRICT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS chk_todos_parent_not_self
    CHECK (parent_id IS NULL OR parent_id <> id);
CREATE INDEX IF NOT EXISTS idx_todos_parent_order ON todos (parent_id, display_order, id);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    color VARCHAR(7) NOT NULL
);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS category_id BIGINT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS fk_todos_category
    FOREIGN KEY (category_id) REFERENCES categories (id);
CREATE INDEX IF NOT EXISTS idx_todos_category_id ON todos (category_id);

CREATE TABLE IF NOT EXISTS assignees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS assignee_id BIGINT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS fk_todos_assignee
    FOREIGN KEY (assignee_id) REFERENCES assignees (id);
CREATE INDEX IF NOT EXISTS idx_todos_assignee_id ON todos (assignee_id);
