CREATE TABLE IF NOT EXISTS todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_todos_display_order_id
    ON todos (display_order, id);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS start_date DATE;
ALTER TABLE todos ADD COLUMN IF NOT EXISTS due_date DATE;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    color VARCHAR(7) NOT NULL
);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS category_id BIGINT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS fk_todos_category
    FOREIGN KEY (category_id) REFERENCES categories (id);
CREATE INDEX IF NOT EXISTS idx_todos_category_id ON todos (category_id);

CREATE TABLE IF NOT EXISTS assignees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

ALTER TABLE todos ADD COLUMN IF NOT EXISTS assignee_id BIGINT;
ALTER TABLE todos ADD CONSTRAINT IF NOT EXISTS fk_todos_assignee
    FOREIGN KEY (assignee_id) REFERENCES assignees (id);
CREATE INDEX IF NOT EXISTS idx_todos_assignee_id ON todos (assignee_id);
